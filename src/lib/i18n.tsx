const DICTS: Record<Lang, Dict> = { en, km };
export const getDict = (l: Lang) => DICTS[l];

interface Ctx {
  lang: Lang;
  t: Dict;
  setLang: (l: Lang) => void;
  /** Compass point name for an azimuth in degrees. */
  dir: (az: number) => string;
}

const LangContext = createContext<Ctx | null>(null);

export function LangProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>('en');

  useEffect(() => {
    let saved: string | null = null;
    try { saved = localStorage.getItem('onesolar.lang'); } catch {}
    if (saved === 'en' || saved === 'km') setLangState(saved);
    else if (navigator.language?.toLowerCase().startsWith('km')) setLangState('km');
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const setLang = (l: Lang) => {
    setLangState(l);
    try { localStorage.setItem('onesolar.lang', l); } catch {}
  };

  const t = DICTS[lang];
  const dir = (az: number) => t.dirs[Math.round((((az % 360) + 360) % 360) / 45) % 8];

  return <LangContext.Provider value={{ lang, t, setLang, dir }}>{children}</LangContext.Provider>;
}

export function useT() {
  const ctx = useContext(LangContext);
  if (!ctx) throw new Error('useT must be used inside <LangProvider>');
  return ctx;
}
